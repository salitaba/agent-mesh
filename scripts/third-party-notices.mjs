#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: every package that ships in the production install, with its version and
 * licence, from package-lock.json alone (so it reads the same on any machine and needs no node_modules).
 *
 *   node scripts/third-party-notices.mjs           write it
 *   node scripts/third-party-notices.mjs --check   exit 1 if it is out of date (a test runs this too)
 *   --lock <file> --out <file>                     read another lockfile / write another file (for tests)
 *
 * The licence TEXTS travel with the packages: each one's LICENSE file is in its own directory under
 * node_modules, which the container image carries. This file is the inventory and the one exception.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
/** `--lock <file>` and `--out <file>` exist so a test can point this at a lockfile of its own. */
const option = (name) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const lock = JSON.parse(fs.readFileSync(option("--lock") ?? path.join(root, "package-lock.json"), "utf8"));

const rows = [];
for (const [location, info] of Object.entries(lock.packages)) {
  // The production tree only: not the project itself, not our own workspace packages (links), not dev tooling.
  if (!location.startsWith("node_modules/") || info.dev || info.link) continue;
  const name = location.slice(location.lastIndexOf("node_modules/") + "node_modules/".length);
  rows.push({ name, version: info.version, license: String(info.license ?? "UNKNOWN"), optional: Boolean(info.optional), peer: Boolean(info.peer) });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const proprietary = rows.filter((r) => r.name.startsWith("@anthropic-ai/claude-agent-sdk"));
const open = rows.filter((r) => !r.name.startsWith("@anthropic-ai/claude-agent-sdk"));
const byLicense = new Map();
for (const r of open) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

const lines = [];
lines.push("# Third-party notices");
lines.push("");
lines.push("Generated by `scripts/third-party-notices.mjs` from `package-lock.json`. Do not edit by hand.");
lines.push("");
lines.push(`Ordane's production install contains ${rows.length} third-party packages. Their licence texts are in each`);
lines.push("package's own directory under `node_modules/`, which the container image carries unchanged.");
lines.push("");
lines.push("## The Claude Agent SDK is not open source");
lines.push("");
lines.push("`@anthropic-ai/claude-agent-sdk`, and the platform packages that carry its `claude` executable, are Anthropic's:");
lines.push("");
lines.push("> © Anthropic PBC. All rights reserved. Use is subject to the Legal Agreements outlined here:");
lines.push("> https://code.claude.com/docs/en/legal-and-compliance");
lines.push("");
lines.push("They are installed from npm and run unmodified, which is how those terms require them to be run. They are not");
lines.push("covered by Ordane's licence. Whoever runs Ordane needs their own agreement with Anthropic (or with Amazon,");
lines.push("Google or Microsoft for their hosting of the models) and their own credentials.");
lines.push("");
lines.push("| Package | Version |");
lines.push("|---|---|");
for (const r of proprietary) lines.push(`| ${r.name}${r.optional ? " (optional, per platform)" : ""} | ${r.version} |`);
lines.push("");
lines.push("## Open-source packages by licence");
lines.push("");
lines.push("| Licence | Packages |");
lines.push("|---|---|");
for (const [license, count] of [...byLicense].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) lines.push(`| ${license} | ${count} |`);
lines.push("");
lines.push("Every one of these is a permissive licence. None is a copyleft licence (GPL, LGPL, AGPL, MPL, EPL or similar); the");
lines.push("generator fails if one appears, so adding such a dependency is a decision somebody makes on purpose.");
lines.push("");
lines.push("## All packages");
lines.push("");
lines.push("| Package | Version | Licence |");
lines.push("|---|---|---|");
for (const r of open) lines.push(`| ${r.name}${r.peer ? " (peer)" : ""}${r.optional ? " (optional)" : ""} | ${r.version} | ${r.license} |`);
lines.push("");
const text = lines.join("\n");

const COPYLEFT = /(^|[\s(])(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|OSL|SSPL|BUSL|CC-BY-NC)/i;
const bad = open.filter((r) => COPYLEFT.test(r.license) || r.license === "UNKNOWN");
if (bad.length > 0) {
  console.error(`licences that need a decision before this product is distributed:\n${bad.map((r) => `  ${r.name}@${r.version}: ${r.license}`).join("\n")}`);
  process.exit(1);
}

const target = option("--out") ?? path.join(root, "THIRD_PARTY_NOTICES.md");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== text) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run `node scripts/third-party-notices.mjs` and commit the result");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date");
} else {
  fs.writeFileSync(target, text, "utf8");
  console.log(`wrote THIRD_PARTY_NOTICES.md (${rows.length} packages)`);
}
