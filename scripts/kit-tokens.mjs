const decl = (set, indent) => Object.entries(set).map(([k, v]) => `${indent}--k-${k}: ${v};`).join("\n");

/**
 * The block for one kind of stylesheet.
 *   "system"   the site and the account pages: light, and the visitor's dark setting switches it (no toggle)
 *   "console"  the console: dark, and `[data-theme="light"]` switches it (the console follows the system until chosen)
 */
export function kitBlock(mode) {
  if (mode === "system") {
    return `${BEGIN}
:root {
${decl(SHARED, "  ")}
${decl(THEMES.light, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root {
${decl(THEMES.dark, "    ")}
  }
}
${END}`;
  }
  if (mode === "console") {
    return `${BEGIN}
:root {
${decl(SHARED, "  ")}
${decl(THEMES.dark, "  ")}
}
[data-theme="light"] {
${decl(THEMES.light, "  ")}
}
${END}`;
  }
  throw new Error(`unknown kit block mode: ${mode}`);
}

/** Every stylesheet that carries the block, and which kind it is. */
export const TARGETS = [
  { file: "site/assets/site.css", mode: "system" },
  { file: "apps/cloud-server/pages/assets/app.css", mode: "system" },
  { file: "apps/mesh-dashboard/src/styles.css", mode: "console" },
];

/** `css` with the text between the fences replaced by `block`. Throws when the fences are missing: a stylesheet must opt in. */
export function inject(css, block, name = "stylesheet") {
  const a = css.indexOf(BEGIN);
  const b = css.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${name} has no ${BEGIN.slice(0, 30)}... fence pair: add the two comments where the kit's tokens go`);
  return css.slice(0, a) + block + css.slice(b + END.length);
}

/** `{ file, want, have }` for every target. `have` is what is on disk, `want` what the kit says it should be. */
export function kitState(base = root) {
  return TARGETS.map(({ file, mode }) => {
    const have = readFileSync(join(base, file), "utf8");
    return { file, have, want: inject(have, kitBlock(mode), file) };
  });
}

/** brand/kit.css: the system-mode block on its own, for a person (or a page) that wants the tokens and nothing else. */
export function kitFile() {
  return `/* Curule UI kit tokens. Generated by scripts/kit-tokens.mjs: change the script, not this file.
   The site, the account pages and the console carry the same values in their own stylesheets. */
${kitBlock("system")}
`;
}

/** Writes every block. Returns the files that changed. */
export function writeKit(base = root) {
  const changed = [];
  for (const s of kitState(base)) {
    if (s.have !== s.want) {
      writeFileSync(join(base, s.file), s.want);
      changed.push(s.file);
    }
  }
  return changed;
}
