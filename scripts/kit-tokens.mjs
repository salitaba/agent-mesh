/*
 * The Curule UI kit's tokens: the values every surface shares, written once.
 *
 * The site, the account pages and the console are three stylesheets for three kinds of page, and they had begun to say the
 * same things in different numbers: three shadows, two greens, four radii. The kit is the part that must be the same
 * everywhere: the colour roles, the elevation ladder, the radii, the tracking and the motion. It is generated into each
 * stylesheet between two fence comments, so no surface can drift from it by being edited by hand:
 *
 *   node scripts/build-brand.mjs           rewrites the blocks (and brand/kit.css, the same tokens on their own)
 *   node scripts/build-brand.mjs --check   exits 1 if a block differs (npm run brand:check)
 *
 * What is not here: the brand's seven colours (brand/tokens.css; this file starts from them, and a test keeps them equal),
 * the console's status colours and role colours (they were derived to a contrast target and are pinned by
 * tests/build/console-palette.test.ts; the kit's status colours are the same values), and any component. A component
 * is built from these in the stylesheet that owns it.
 *
 * Names: every token here is `--k-*`. A stylesheet's own names (`--bg`, `--panel`, `--accent` ...) may alias them.
 */
